-- Road graph checks: the issues of the editing session are stored in the table graph_issues
--
-- The algorithm Check the road graph stores the issues of the editing session in the table
-- road_graph_editing.graph_issues, displayed by two layers of the project, instead of creating new layers
-- at each run. The table is emptied when the data is copied to a new editing session,
-- and when the editing session is merged or dropped.
--
-- refresh_graph_issues: runs the checks and updates the stored issues of the given checks and roads:
-- the issues still found keep their id, the issues not found anymore are deleted, the new ones are added.
-- fix_stored_graph_issue: fixes a stored issue, stores the result, then checks again the roads of the issue.

-- graph_issues
CREATE TABLE IF NOT EXISTS road_graph.graph_issues (
    id integer NOT NULL,
    check_code text NOT NULL,
    check_title text,
    severity text,
    road_code text,
    edge_ids integer[],
    node_ids integer[],
    marker_ids integer[],
    details jsonb,
    fix_action text,
    fix_params jsonb,
    fix_status text,
    fix_message text,
    checked_at timestamp without time zone DEFAULT (now())::timestamp(0) without time zone,
    geom geometry(Point, 2154),
    geom_detail geometry(MultiLineString, 2154),
    CONSTRAINT graph_issues_fix_status_values CHECK ((fix_status = ANY (ARRAY['success'::text, 'skipped'::text, 'error'::text])))
);

-- graph_issues_id_seq
ALTER TABLE road_graph.graph_issues ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME road_graph.graph_issues_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

