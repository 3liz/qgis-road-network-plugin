def finalize_roundabout(layer_id: str, road_code: str, road_type: str):
    """
    Finalize the roundabout digitized with the QGIS circle tool:
    delete the internal edges and merge the top edges.

    These lines are included in the QGIS project, in the layer "edges copie".

        from qgis.utils import plugins
        plugins['roadnetwork'].run_action(
            'finalize_roundabout',
            layer_id='[% @layer_id %]',
            road_code='[% road_code %]',
            road_type='[% roads_road_type %]',
        )
    """
    action_name = tr("Cannot finalize the roundabout")

    layer = get_postgres_layer(layer_id, action_name)
    if layer is None:
        # Error message already displayed
        return

    if not layer.isEditable():
        display_message(
            action_name,
            tr("You must first activate the editing mode on the layer {}").format(layer.name()),
            Qgis.MessageLevel.Warning,
        )
        return

    if road_type != "roundabout":
        display_message(
            tr("The edge is not part of a roundabout"),
            tr("Its road type is {}. No action.").format(road_type),
            Qgis.MessageLevel.Warning,
        )
        return

    # Merge the top edges around the circle top node
    # generated by QGIS circle digitizing tool
    sql = "SELECT road_graph_editing.clean_digitized_roundabout({}) AS returned_result".format(
        quote_literal(road_code)
    )
    if not execute_sql_in_layer_transaction(layer, sql, tr("Error occurred while cleaning the roundabout")):
        return

    display_message(
        tr("The roundabout {} has been successfully finalized").format(road_code),
        tr("You may have to refresh the map canvas to see the changes"),
        Qgis.MessageLevel.Success,
    )
    layer.triggerRepaint()


def display_edited_data(logged_ids: str):
    """
    Flash the objects inserted, updated or deleted in the editing session.

    These lines are included in the QGIS project, in the layer "editing_sessions".

        from qgis.utils import plugins
        plugins['roadnetwork'].run_action(
            'display_edited_data',
            logged_ids='[% to_json(logged_ids) %]',
        )

    The logged_ids JSON looks like:
        {
            "edges": {"3184": "U", "6854": "D", "7854": "I"},
            "nodes": {"3146": "D", "5784": "I"},
            "markers": {"3249": "U", "8348": "I"}
        }
    """
    try:
        logs_by_layer = json.loads(logged_ids)
    except json.JSONDecodeError:
        logs_by_layer = {}
    if not isinstance(logs_by_layer, dict) or not logs_by_layer:
        display_message(
            tr("Display edited data"),
            tr("No edited data in this editing session"),
            Qgis.MessageLevel.Info,
        )
        return

    canvas = iface.mapCanvas()
    project = QgsProject.instance()

    # Highlight colors
    flash_colors = {
        "I": (QColor(0, 255, 0, 255), QColor(0, 255, 0, 100)),
        "U": (QColor(255, 255, 0, 255), QColor(255, 255, 0, 100)),
        "D": (QColor(255, 0, 0, 255), QColor(255, 0, 0, 100)),
    }

    # Use a list to order the flashes based on the action type
    flash_order = ("U", "D", "I")

    for layer_name, logs in logs_by_layer.items():
        # The inserted and updated objects are displayed with the editing layer,
        # the deleted ones with the original layer
        clone_layers = project.mapLayersByName(f"{layer_name} copie")
        source_layers = project.mapLayersByName(layer_name)

        for action in flash_order:
            ids = [int(object_id) for object_id, action_code in logs.items() if action_code == action]
            if not ids:
                continue

            target_layers = source_layers if action == "D" else clone_layers
            if not target_layers or not isinstance(target_layers[0], QgsVectorLayer):
                display_error_message(
                    tr("Display edited data"),
                    tr("Layer not found with name {}").format(
                        layer_name if action == "D" else f"{layer_name} copie"
                    ),
                )
                continue

            canvas.flashFeatureIds(
                target_layers[0],
                ids,
                startColor=flash_colors[action][0],
                endColor=flash_colors[action][1],
                flashes=8,
                duration=500,
            )


def create_editing_session():
    """
    Open the algorithm dialog to create a new editing session.

    These lines are included in the QGIS project, in the layer "editing_sessions".

        from qgis.utils import plugins
        plugins['roadnetwork'].run_action('create_editing_session')
    """
    processing.execAlgorithmDialog("roadnetwork:create_editing_session", {})


def drop_editing_session(layer_id: str, editing_session_id: int):
    """
    Delete the editing session and the data of the road_graph_editing schema.

    These lines are included in the QGIS project, in the layer "editing_sessions".

        from qgis.utils import plugins
        plugins['roadnetwork'].run_action(
            'drop_editing_session',
            layer_id='[% @layer_id %]',
            editing_session_id=[% id %],
        )
    """
    action_name = tr("Cannot drop the editing session")

    reply = QMessageBox.question(
        iface.mainWindow(),
        tr("Drop editing session"),
        tr("Are you sure you want to delete this editing session and its related data ?"),
        QMessageBox.StandardButton.Yes,
        QMessageBox.StandardButton.No,
    )
    if reply != QMessageBox.StandardButton.Yes:
        return

    layer = get_postgres_layer(layer_id, action_name)
    if layer is None:
        # Error message already displayed
        return

    if not layer.isEditable():
        display_message(
            action_name,
            tr('You must first activate the "editing mode" on the layer {}').format(layer.name()),
            Qgis.MessageLevel.Warning,
        )
        return

    listening = QgsExpressionContextUtils.projectScope(QgsProject.instance()).variable(
        "road_network_listen_move_event"
    )
    if listening == "True":
        display_message(
            action_name,
            tr(
                'You must first uncheck the checkbox "Get references on hover ?" '
                'in the "Road network tools" dock widget'
            ),
            Qgis.MessageLevel.Warning,
        )
        return

    sql = f"SELECT road_graph.drop_editing_session({editing_session_id}) AS returned_result"
    if not execute_sql_in_layer_transaction(
        layer, sql, tr("Error occurred while dropping the editing session")
    ):
        return

    display_message(
        tr("The editing session has been successfully deleted and related data have been dropped."),
        tr("You may have to refresh the map canvas to see the changes"),
        Qgis.MessageLevel.Success,
    )
    layer.triggerRepaint()
